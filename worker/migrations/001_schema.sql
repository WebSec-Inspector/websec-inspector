CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE, password_hash varchar(255) NOT NULL,
    name varchar(255) NOT NULL, role varchar(255) NOT NULL,
    manager_id bigint REFERENCES users(id), created_at timestamptz NOT NULL
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS manager_id bigint REFERENCES users(id);
CREATE TABLE IF NOT EXISTS domains (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id), hostname varchar(255) NOT NULL,
    verification_token varchar(255) NOT NULL UNIQUE, verified_at timestamptz,
    UNIQUE(hostname,user_id)
);
CREATE TABLE IF NOT EXISTS scans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id bigint NOT NULL REFERENCES domains(id), name varchar(120),
    status varchar(255) NOT NULL CHECK(status IN ('PENDING_VERIFICATION','QUEUED','RUNNING','COMPLETED','FAILED')),
    created_at timestamptz NOT NULL, started_at timestamptz, finished_at timestamptz, deleted_at timestamptz
);
ALTER TABLE scans ADD COLUMN IF NOT EXISTS name varchar(120), ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
CREATE TABLE IF NOT EXISTS findings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id bigint NOT NULL REFERENCES scans(id), owasp_category varchar(255) NOT NULL,
    description text NOT NULL, cvss_score double precision NOT NULL,
    severity varchar(255) NOT NULL, recommendation text
);
CREATE TABLE IF NOT EXISTS reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id bigint NOT NULL UNIQUE REFERENCES scans(id), pdf_url varchar(255) NOT NULL, sent_at timestamptz
);
